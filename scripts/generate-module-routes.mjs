#!/usr/bin/env node
/**
 * Generate Next.js App Router stubs for plugin module routes that lack a page.tsx.
 * Built-in features keep hand-written pages under app/.
 *
 * Usage: npm run generate:routes
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const APP_ROOT = join(ROOT, "apps/web/src/app");
const WEB_SRC = join(ROOT, "apps/web/src");
const PLUGINS_ROOT = join(WEB_SRC, "plugins");

const ROUTE_ENTRY_RE = /\{\s*path:\s*["']([^"']+)["']\s*,\s*component:\s*["']([^"']+)["']\s*\}/g;
const EXPORT_RE = (name) => new RegExp(`export\\s+(?:async\\s+)?(?:function|const)\\s+${name}\\b`);

function walkModuleFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      out.push(...walkModuleFiles(full));
    } else if (name === "module.ts") {
      out.push(full);
    }
  }
  return out;
}

function toImportAlias(absPath) {
  const rel = relative(WEB_SRC, absPath).replace(/\\/g, "/").replace(/\.tsx?$/, "");
  return `@/${rel}`;
}

function resolveScreenImport(moduleDir, exportName) {
  for (const name of readdirSync(moduleDir)) {
    if (!name.endsWith(".tsx") && !name.endsWith(".ts")) continue;
    if (name === "module.ts" || name === "index.ts") continue;
    const full = join(moduleDir, name);
    const text = readFileSync(full, "utf8");
    if (EXPORT_RE(exportName).test(text)) {
      return { importPath: toImportAlias(full), exportName };
    }
  }
  return null;
}

function collectPluginRoutes() {
  if (!existsSync(PLUGINS_ROOT)) return [];
  const routes = [];
  for (const file of walkModuleFiles(PLUGINS_ROOT)) {
    const text = readFileSync(file, "utf8");
    const moduleDir = dirname(file);
    for (const match of text.matchAll(ROUTE_ENTRY_RE)) {
      const path = match[1];
      const component = match[2];
      const exportName = component.split("/").pop();
      const screen = resolveScreenImport(moduleDir, exportName);
      if (!screen) {
        console.warn(`skip ${path}: no screen exporting ${exportName} beside ${relative(ROOT, file)}`);
        continue;
      }
      routes.push({ path, ...screen });
    }
  }
  return routes.sort((a, b) => a.path.localeCompare(b.path));
}

function pagePath(routePath) {
  const segments = routePath.replace(/^\//, "").split("/").filter(Boolean);
  return join(APP_ROOT, ...segments, "page.tsx");
}

function stubFor({ importPath, exportName }) {
  return `// AUTO-GENERATED by scripts/generate-module-routes.mjs — do not edit.
import { Suspense } from "react";
import { ${exportName} } from "${importPath}";

export default function PluginModulePage() {
  return (
    <Suspense fallback={null}>
      <${exportName} />
    </Suspense>
  );
}
`;
}

let created = 0;
for (const route of collectPluginRoutes()) {
  const target = pagePath(route.path);
  if (existsSync(target)) continue;
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, stubFor(route), "utf8");
  created++;
  console.log("created", relative(ROOT, target));
}

console.log(created ? `Done — ${created} route stub(s).` : "No new plugin routes to generate.");
