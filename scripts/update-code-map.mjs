#!/usr/bin/env node
/**
 * The size table in `docs/architecture-map.md`, counted rather than remembered.
 *
 * Numbers in prose rot silently: nobody notices that "22,000 lines" became
 * 31,000, and a reader who checks one figure and finds it wrong stops trusting
 * the rest of the page. So the table is generated between two markers and the
 * words around it are not — the document keeps its argument, and the arithmetic
 * stops being anyone's job.
 *
 *   node scripts/update-code-map.mjs            rewrite the block
 *   node scripts/update-code-map.mjs --check    fail if it is out of date
 *
 * `--check` is what CI runs, so a change that moves the counts has to carry the
 * regenerated table with it, the same way a lockfile travels with a dependency.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DOC = path.join(ROOT, "docs/architecture-map.md");
const START = "<!-- code-map:start -->";
const END = "<!-- code-map:end -->";

/** Anything generated, installed, or built. None of it is ours to count. */
const SKIP_DIRS = new Set([
  "node_modules", ".next", ".git", "dist", "out", "release", "coverage",
  "__pycache__", ".venv", "venv", ".turbo", "playwright-report", "test-results",
]);

const CODE = new Set([".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".py", ".css", ".sql"]);

/**
 * One row of the table: where it is, what it is for, and how it is measured.
 *
 * `count` is either lines of code or a file tally, because for two of these the
 * honest unit is files — a migration is a step in a sequence whether it is four
 * lines or four hundred, and so is a page of documentation.
 */
const AREAS = [
  { dir: "packages/core", unit: "lines", what: "Domain and application logic shared by every surface" },
  { dir: "apps/web", unit: "lines", what: "The app itself: screens, features, API routes, backend wiring" },
  { dir: "apps/desktop", unit: "lines", what: "The Electron shell — what only an installed app can do" },
  { dir: "apps/pitch", unit: "lines", what: "The public site and this documentation" },
  { dir: "python/weaveforge", unit: "lines", what: "The SDK training scripts import" },
  { dir: "python/tests", unit: "lines", what: "Its tests" },
  { dir: "supabase/migrations", unit: "files", what: "The schema, as an ordered sequence" },
  { dir: "docs", unit: "files", what: "Documentation, this page included" },
];

function walk(dir, onFile) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return; // A folder that is not checked out is not a folder with no code.
  }
  for (const entry of entries) {
    if (entry.name.startsWith(".") && entry.name !== ".gitignore") continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) walk(full, onFile);
    } else {
      onFile(full);
    }
  }
}

function measure({ dir, unit }) {
  const full = path.join(ROOT, dir);
  let lines = 0;
  let files = 0;
  walk(full, (file) => {
    const ext = path.extname(file);
    if (unit === "files") {
      if (ext === ".sql" || ext === ".md") files += 1;
      return;
    }
    if (!CODE.has(ext)) return;
    files += 1;
    // Counted the way `wc -l` counts: a trailing newline does not open a line.
    const text = readFileSync(file, "utf8");
    if (text) lines += text.split("\n").length - (text.endsWith("\n") ? 1 : 0);
  });
  return { lines, files };
}

function table() {
  const rows = AREAS.map((area) => ({ ...area, ...measure(area) }));
  const totalLines = rows.filter((r) => r.unit === "lines").reduce((sum, r) => sum + r.lines, 0);
  const n = (value) => value.toLocaleString("en-US");

  const body = rows.map((row) =>
    `| \`${row.dir}\` | ${row.unit === "files" ? `${n(row.files)} files` : `${n(row.lines)} lines`} | ${row.what} |`,
  );

  return [
    START,
    "",
    `<!-- Generated by scripts/update-code-map.mjs — run \`npm run map\` after a change that moves these. -->`,
    "",
    "| Where | Size | What lives there |",
    "| --- | --- | --- |",
    ...body,
    "",
    `**${n(totalLines)} lines of code in all**, across ${n(rows.filter((r) => r.unit === "lines").reduce((sum, r) => sum + r.files, 0))} source files.`,
    "",
    END,
  ].join("\n");
}

const doc = readFileSync(DOC, "utf8");
const newline = doc.includes("\r\n") ? "\r\n" : "\n";
const from = doc.indexOf(START);
const to = doc.indexOf(END);
if (from === -1 || to === -1) {
  console.error(`${path.relative(ROOT, DOC)} has no ${START} / ${END} block to fill.`);
  process.exit(1);
}

const next = doc.slice(0, from) + table().split("\n").join(newline) + doc.slice(to + END.length);

if (process.argv.includes("--check")) {
  if (next === doc) {
    console.log("code map: up to date");
    process.exit(0);
  }
  console.error("code map: out of date — run `npm run map` and commit the result.");
  process.exit(1);
}

writeFileSync(DOC, next);
console.log(`code map: rewrote the table in ${path.relative(ROOT, DOC)}`);
