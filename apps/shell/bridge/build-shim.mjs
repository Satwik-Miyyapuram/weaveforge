// Bundles the bridge into the script the shell injects into its main window (apps/shell/src/shim.rs).
// Usage: node apps/shell/bridge/build-shim.mjs          writes shim.gen.js
//        node apps/shell/bridge/build-shim.mjs --check  fails when shim.gen.js is stale
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../../..");
const outfile = path.join(here, "shim.gen.js");
const req = createRequire(path.join(repo, "package.json"));
const { build } = await import(pathToFileURL(req.resolve("esbuild")).href);

const result = await build({
  entryPoints: [path.join(here, "inject.ts")],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2022",
  charset: "utf8",
  legalComments: "none",
  // @tauri-apps/api is not a dependency; tauri-core.ts talks to the same internals.
  alias: { "@tauri-apps/api/core": path.join(here, "tauri-core.ts") },
  tsconfig: path.join(here, "tsconfig.json"),
  logLevel: "warning",
});
const banner = "// Generated by apps/shell/bridge/build-shim.mjs from inject.ts. Do not edit.\n";
// Same bytes on every OS: esbuild writes LF, and no absolute paths go in.
const text = banner + new TextDecoder().decode(result.outputFiles[0].contents);

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outfile) ? fs.readFileSync(outfile, "utf8") : "";
  if (current !== text) {
    console.error("apps/shell/bridge/shim.gen.js is stale. Run: node apps/shell/bridge/build-shim.mjs");
    process.exit(1);
  }
} else {
  fs.writeFileSync(outfile, text);
  console.log(`wrote ${path.relative(repo, outfile)} (${text.length} bytes)`);
}
