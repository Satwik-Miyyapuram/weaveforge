-- Fix A of docs/internal/future-work/metrics-storage-plan.md — narrow the metric rows.
--
-- `experiment_metrics` is the only table in the schema that grows without
-- bound, so it alone decides when the 50 GB `pgdata` volume fills — and OCI
-- Always Free caps every volume at 200 GB combined, so there is nowhere to grow
-- into. Measured on the live table before this ran: 448.7 B per point.
--
-- Roughly half of that was a surrogate key nothing queries and a string
-- repeated on every row:
--
--   * `id uuid`      a random primary key no query ever filtered on, costing
--                    16 B of heap plus a whole 112 kB index
--   * `metric text`  ten distinct values in the entire table, stored in full on
--                    every row *and* again in every entry of the series index
--   * `created_at`   redundant with `wall_time`
--
-- What replaces them: a lookup table for the names, and `(experiment_id,
-- metric_id, step)` as the primary key — which is the access pattern anyway, so
-- the series index stops being a second copy of the same thing.
--
-- `metric_id` is `int`, not the `smallint` the plan proposed. Measured at 200k
-- points the two are byte-identical — alignment padding between `metric_id` and
-- `step` swallows the difference — so `smallint` bought nothing and would have
-- capped the *whole deployment* at 32767 distinct metric names, shared across
-- every tenant. Free safety.
--
-- `user_id` stays. Dropping it measures 23.3 B/point cheaper again, but RLS
-- would have to reach `experiments` through a join on every row; the plan calls
-- that a trade rather than a win, and it is not this migration's business.
--
-- ⚠️ Uniqueness. The new primary key asserts something the old schema did not,
-- and the live table did *not* satisfy it: 86 rows across 2 experiments were
-- duplicate `(experiment_id, metric, step)`. Every one was an exact re-ingest —
-- identical `value` and `wall_time` — i.e. a batch delivered twice, so
-- collapsing them loses no measurement. That is verified below rather than
-- assumed: the dedup only removes rows whose value and wall_time match the row
-- being kept, and the primary key would fail loudly if any disagreed.
--
-- Compatibility. `experiment_metrics` becomes a view over the narrowed table
-- that still presents `metric` as text, with INSTEAD OF triggers doing the name
-- lookup on write. Every existing caller — the SDK ingest route, both metric
-- repositories, the Python SDK, the showcase seed — keeps working untouched.
-- That seam is also what lets Fix B swap the storage underneath for chunked
-- arrays without any reader above the repository knowing.
--
-- Reversal: supabase/migrations-rollback/0114_experiment_metrics_narrow_rows.sql
--
-- Re-runnable: every step is guarded, and the whole conversion is skipped once
-- `experiment_metrics` is already a view.

-- ---------------------------------------------------------------------------
-- 1. The name lookup.
-- ---------------------------------------------------------------------------

create table if not exists experiment_metric_names (
  id   int generated by default as identity primary key,
  name text not null unique
);

alter table experiment_metric_names enable row level security;

-- Names are not user data: they are a shared dictionary of strings like "loss".
-- Every authenticated caller may read them, because expanding a stored
-- `metric_id` back into text requires it. Writes go only through
-- `experiment_metric_name_id()`, which is security definer.
drop policy if exists "experiment_metric_names_select_all" on experiment_metric_names;
create policy "experiment_metric_names_select_all" on experiment_metric_names
  for select to authenticated using (true);

grant select on experiment_metric_names to authenticated;
grant select, insert, update, delete on experiment_metric_names to service_role;
grant usage, select on all sequences in schema public to authenticated, service_role;

/**
 * Resolve a metric name to its id, creating it on first sight.
 *
 * Security definer because callers are only granted SELECT on the lookup —
 * inserting a name is a side effect of logging a metric, not a privilege worth
 * handing out directly. The `on conflict … do update` is what makes it safe
 * under concurrency: two runs logging a brand-new metric name at the same
 * moment both get the same id instead of one raising a unique violation.
 * `do update` rather than `do nothing` because only the former returns a row.
 */
create or replace function experiment_metric_name_id(p_name text)
returns int
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id int;
begin
  if p_name is null then
    raise exception 'metric name is required';
  end if;

  select id into v_id from experiment_metric_names where name = p_name;
  if v_id is not null then
    return v_id;
  end if;

  insert into experiment_metric_names (name) values (p_name)
    on conflict (name) do update set name = excluded.name
    returning id into v_id;
  return v_id;
end;
$$;

revoke all on function experiment_metric_name_id(text) from public;
grant execute on function experiment_metric_name_id(text) to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 2. Convert the table — skipped entirely once it is already a view.
-- ---------------------------------------------------------------------------

-- Built fresh and swapped in, rather than altered in place.
--
-- `alter table … drop column` reclaims nothing: Postgres only marks the
-- attribute dropped, and every tuple written before that keeps carrying the old
-- values until something rewrites the table. Measured — the in-place version of
-- this migration moved the live table from 448.7 to 441.8 B/row, a 1.5% "win"
-- that was really three `........pg.dropped.N........` ghosts still occupying
-- each row, plus the dead tuples left by backfilling `metric_id`. A rewrite is
-- the point of the exercise, so do it explicitly.
--
-- The whole file is one implicit transaction, which also rules out `vacuum
-- full` — it cannot run inside one. Build, copy, swap.

do $$
begin
  if to_regclass('public.experiment_metrics') is null then
    return;                                  -- nothing to convert yet
  end if;
  if (select relkind from pg_class where oid = 'public.experiment_metrics'::regclass) <> 'r' then
    return;                                  -- already converted
  end if;

  -- Seed the lookup from whatever names the table already holds.
  insert into experiment_metric_names (name)
  select distinct metric from experiment_metrics
  on conflict (name) do nothing;

  -- Column order is deliberate: 16 + 16 + 8 + 8 + 4 + 4 packs into exactly 56
  -- bytes with no alignment padding. The same columns declared widest-last
  -- would pad `metric_id`/`step` out and cost bytes for nothing.
  create table experiment_metric_points (
    experiment_id uuid not null references experiments(id) on delete cascade,
    user_id       uuid not null references auth.users(id),
    value         double precision not null,
    wall_time     timestamptz,
    metric_id     int not null references experiment_metric_names(id),
    step          int not null,
    primary key (experiment_id, metric_id, step)
  );

  -- `distinct on` collapses the exact re-ingests while copying, so the rewrite
  -- and the dedup are the same pass and no dead tuples are produced.
  --
  -- Ordering by `value, wall_time` inside the group makes the choice
  -- deterministic. It only ever matters for rows that are *not* exact copies —
  -- and there are none today (verified: 86 duplicate groups, 0 with differing
  -- values). If that ever changes, the assertion below stops the migration
  -- rather than letting it silently discard a real measurement.
  if exists (
    select 1 from experiment_metrics
    group by experiment_id, metric, step
    having count(distinct value) > 1
        or count(distinct coalesce(wall_time, 'epoch'::timestamptz)) > 1
  ) then
    raise exception
      'experiment_metrics has (experiment_id, metric, step) duplicates that disagree on value or wall_time; '
      'these are real measurements, not re-ingests, and the new primary key cannot represent them. '
      'Resolve them before applying 0114.';
  end if;

  insert into experiment_metric_points (experiment_id, user_id, value, wall_time, metric_id, step)
  select distinct on (m.experiment_id, n.id, m.step)
         m.experiment_id, m.user_id, m.value, m.wall_time, n.id, m.step
    from experiment_metrics m
    join experiment_metric_names n on n.name = m.metric
   order by m.experiment_id, n.id, m.step, m.value, m.wall_time;

  drop table experiment_metrics;

  -- The old series index was `(experiment_id, metric, step)`; the primary key
  -- now covers exactly that access pattern, so it is not recreated. `user_id`
  -- keeps its index — RLS filters on it.
  create index experiment_metric_points_user_id_idx on experiment_metric_points (user_id);
end;
$$;

-- ---------------------------------------------------------------------------
-- 2b. RLS on the narrowed table.
-- ---------------------------------------------------------------------------

-- Recreated here rather than inherited: the policies from 0087 belonged to the
-- table this migration dropped. Same rules, same names, now on the new table.
alter table experiment_metric_points enable row level security;

drop policy if exists "experiment_metrics_select_access" on experiment_metric_points;
create policy "experiment_metrics_select_access" on experiment_metric_points
  for select using (
    (select auth.uid()) = user_id
    or shared_to_me('experiment', experiment_id)
  );

drop policy if exists "experiment_metrics_insert_own" on experiment_metric_points;
create policy "experiment_metrics_insert_own" on experiment_metric_points
  for insert with check ((select auth.uid()) = user_id);

drop policy if exists "experiment_metrics_update_own" on experiment_metric_points;
create policy "experiment_metrics_update_own" on experiment_metric_points
  for update using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "experiment_metrics_delete_own" on experiment_metric_points;
create policy "experiment_metrics_delete_own" on experiment_metric_points
  for delete using ((select auth.uid()) = user_id);

grant select, insert, update, delete on experiment_metric_points to authenticated;
grant select, insert, update, delete on experiment_metric_points to service_role;

-- ---------------------------------------------------------------------------
-- 3. The compatibility view.
-- ---------------------------------------------------------------------------

-- `security_invoker` so the base table's RLS is evaluated as the caller. The
-- policies rode along with the table through the rename, so ownership and
-- sharing rules are unchanged — without this flag the view would run as its
-- owner and quietly hand every row to everyone.
create or replace view experiment_metrics
  with (security_invoker = true)
as
  select p.user_id,
         p.experiment_id,
         n.name as metric,
         p.step,
         p.value,
         p.wall_time
    from experiment_metric_points p
    join experiment_metric_names n on n.id = p.metric_id;

grant select, insert, update, delete on experiment_metrics to authenticated;
grant select, insert, update, delete on experiment_metrics to service_role;

/**
 * Writes arriving as `metric text` land on the narrowed table.
 *
 * `on conflict … do update` makes re-ingest idempotent. The duplicates this
 * migration cleaned up exist because a batch was delivered twice and the old
 * schema happily stored both copies; under the new primary key that would now
 * be an error, which would turn a harmless retry into a failed run. Last write
 * wins instead.
 */
create or replace function experiment_metrics_insert()
returns trigger
language plpgsql
security invoker
as $$
begin
  insert into experiment_metric_points (user_id, experiment_id, metric_id, step, value, wall_time)
  values (
    coalesce(new.user_id, auth.uid()),       -- the table default the view cannot carry
    new.experiment_id,
    experiment_metric_name_id(new.metric),
    coalesce(new.step, 0),
    new.value,
    new.wall_time
  )
  on conflict (experiment_id, metric_id, step)
  do update set value = excluded.value, wall_time = excluded.wall_time;
  return new;
end;
$$;

drop trigger if exists experiment_metrics_insert_trg on experiment_metrics;
create trigger experiment_metrics_insert_trg
  instead of insert on experiment_metrics
  for each row execute function experiment_metrics_insert();

create or replace function experiment_metrics_update()
returns trigger
language plpgsql
security invoker
as $$
begin
  update experiment_metric_points
     set value     = new.value,
         wall_time = new.wall_time,
         step      = new.step,
         metric_id = experiment_metric_name_id(new.metric)
   where experiment_id = old.experiment_id
     and metric_id     = experiment_metric_name_id(old.metric)
     and step          = old.step;
  return new;
end;
$$;

drop trigger if exists experiment_metrics_update_trg on experiment_metrics;
create trigger experiment_metrics_update_trg
  instead of update on experiment_metrics
  for each row execute function experiment_metrics_update();

create or replace function experiment_metrics_delete()
returns trigger
language plpgsql
security invoker
as $$
begin
  delete from experiment_metric_points
   where experiment_id = old.experiment_id
     and metric_id     = experiment_metric_name_id(old.metric)
     and step          = old.step;
  return old;
end;
$$;

drop trigger if exists experiment_metrics_delete_trg on experiment_metrics;
create trigger experiment_metrics_delete_trg
  instead of delete on experiment_metrics
  for each row execute function experiment_metrics_delete();
