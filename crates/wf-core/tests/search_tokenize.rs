#[test]
fn every_option_combination_matches_the_typescript() {
    assert_eq!(OPTION_CASES.len(), 32);
    for (input, mask, tokens, terms) in OPTION_CASES {
        let options = options_for(*mask);
        assert_eq!(
            tokenize(input, &options),
            *tokens,
            "tokenize({input:?}, {mask})"
        );
        assert_eq!(
            index_terms(input, &options),
            *terms,
            "index_terms({input:?}, {mask})"
        );
    }
}

/// Text that mixes the shapes the tokenizer branches on: ASCII case changes,
/// digits, URL punctuation, accents, Greek, CJK, Arabic marks, astral letters.
fn mixed_text() -> impl Strategy<Value = String> {
    prop_oneof![
        r"\PC{0,48}",
        "[a-zA-Z0-9 _.:/\u{e9}\u{c9}\u{3a3}\u{7de8}\u{78bc}\u{30c6}\u{64e}\u{645}\u{1d400}\u{130}\u{212a}-]{0,48}",
        r"(https?://|www\.|[a-z]{1,4}\.(com|io|dev)|[A-Z][a-z]{1,3}| ){0,8}",
    ]
}

proptest! {
    #![proptest_config(ProptestConfig::with_cases(256))]

    #[test]
    fn tokenize_yields_distinct_non_empty_tokens(text in mixed_text(), mask in 0u8..16) {
        let options = options_for(mask);
        let tokens = tokenize(&text, &options);
        prop_assert!(tokens.iter().all(|token| !token.is_empty()));
        let distinct: BTreeSet<&String> = tokens.iter().collect();
        prop_assert_eq!(distinct.len(), tokens.len());
        prop_assert_eq!(index_terms(&text, &options).len(), tokens.len());
    }

    #[test]
    fn url_parts_are_at_least_two_utf16_units(text in mixed_text()) {
        for part in url_parts(&text) {
            prop_assert!(utf16_len(&part) >= MIN_TOKEN_UTF16_LEN);
        }
    }
}
