/// The TS defaults: fold on, Arabic off, camelCase on, URLs on.
const DEFAULTS: TokenizerOptions = TokenizerOptions {
    fold_diacritics: true,
    fold_arabic_diacritics: false,
    split_camel_case: true,
    tokenize_urls: true,
};

/// Mask bits as in the generator: 1 fold, 2 Arabic, 4 camelCase, 8 URLs.
const fn options_for(mask: u8) -> TokenizerOptions {
    TokenizerOptions {
        fold_diacritics: mask & 1 != 0,
        fold_arabic_diacritics: mask & 2 != 0,
        split_camel_case: mask & 4 != 0,
        tokenize_urls: mask & 8 != 0,
    }
}

